create function crs_private.notify_stock_summary() returns void
language plpgsql security definer set search_path = ''
as $$
declare
  payload jsonb;
  attention_total bigint;
begin
  select count(*) into attention_total
  from public.crs_materials
  where coalesce(is_deleted, false) = false
    and remaining_qty <= min_alert;

  select jsonb_build_object(
    'total', count(*),
    'normal', count(*) filter (where remaining_qty > min_alert),
    'low', count(*) filter (where remaining_qty > 0 and remaining_qty <= min_alert),
    'out', count(*) filter (where remaining_qty <= 0),
    'attention', coalesce((
      select jsonb_agg(item)
      from (
        select jsonb_build_object(
          'name', name,
          'remaining_qty', remaining_qty,
          'unit', unit,
          'min_alert', min_alert
        ) as item
        from public.crs_materials
        where coalesce(is_deleted, false) = false
          and remaining_qty <= min_alert
        order by remaining_qty asc, name asc
        limit 20
      ) t
    ), '[]'::jsonb),
    'more_count', greatest(0, attention_total - 20)
  )
  into payload
  from public.crs_materials
  where coalesce(is_deleted, false) = false;

  perform crs_private.post_line(jsonb_build_object('event', 'stock_summary', 'record', payload));
end;
$$;

create function crs_private.notify_overdue_jobs() returns void
language plpgsql security definer set search_path = ''
as $$
declare
  today_th date := (now() at time zone 'Asia/Bangkok')::date;
  payload jsonb;
  overdue_total bigint;
begin
  -- Overdue = event_date strictly before today (Bangkok) and not finished/cancelled.
  select count(*) into overdue_total
  from public.crs_job_orders
  where event_date is not null
    and event_date < today_th
    and coalesce(status, '') not in ('completed', 'cancelled');

  -- Nothing overdue today: stay quiet.
  if overdue_total = 0 then
    return;
  end if;

  select jsonb_build_object(
    'count', overdue_total,
    'jobs', coalesce((
      select jsonb_agg(item)
      from (
        select jsonb_build_object(
          'job_id', job_id,
          'customer_name', customer_name,
          'event_name', event_name,
          'event_date', event_date,
          'days_overdue', (today_th - event_date)
        ) as item
        from public.crs_job_orders
        where event_date is not null
          and event_date < today_th
          and coalesce(status, '') not in ('completed', 'cancelled')
        order by event_date asc, job_id asc
        limit 20
      ) t
    ), '[]'::jsonb),
    'more_count', greatest(0, overdue_total - 20)
  )
  into payload;

  perform crs_private.post_line(jsonb_build_object('event', 'overdue_jobs', 'record', payload));
end;
$$;

