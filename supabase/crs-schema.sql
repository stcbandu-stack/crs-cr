create function crs_private.post_line(payload jsonb) returns void
language plpgsql security definer set search_path = ''
as $$
declare
  secret text;
begin
  select decrypted_secret into secret
  from vault.decrypted_secrets
  where name = 'crs_line_notify_secret';

  if secret is null then
    raise warning 'crs_line_notify_secret not found in vault; skipping LINE notification';
    return;
  end if;

  perform net.http_post(
    url := 'https://ibghmzymkvksqqdwhnyo.supabase.co/functions/v1/crs-line-notify',
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-notify-secret', secret),
    body := payload
  );
end;
$$;

create function crs_private.notify_line() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  perform crs_private.post_line(jsonb_build_object(
    'event', case when tg_op = 'INSERT' then 'new_order' else 'job_completed' end,
    'record', jsonb_build_object(
      'job_id', new.job_id,
      'customer_name', new.customer_name,
      'event_name', new.event_name,
      'event_date', new.event_date,
      'total_price', new.total_price,
      'created_by', new.created_by,
      'item_count', coalesce(jsonb_array_length(new.items), 0)
    )
  ));
  return new;
end;
$$;

