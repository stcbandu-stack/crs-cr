-- ---------- Access: CRS members only ----------

create function crs_private.is_member() returns boolean
language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.crs_profiles where id = auth.uid()) $$;

create function crs_private.is_admin() returns boolean
language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.crs_profiles where id = auth.uid() and role = 'admin') $$;

grant usage on schema crs_private to authenticated;
revoke execute on all functions in schema crs_private from public, anon;
grant execute on function crs_private.is_member(), crs_private.is_admin() to authenticated;

do $$
declare t text;
begin
  foreach t in array array[
    'crs_provider_info','crs_profiles','crs_customers','crs_services','crs_job_orders',
    'crs_materials','crs_material_logs','crs_user_sessions','crs_line_webhook_sources',
    'crs_claims','crs_rental_assets','crs_rentals','crs_rental_items']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
  end loop;

  foreach t in array array[
    'crs_provider_info','crs_customers','crs_services','crs_job_orders','crs_materials',
    'crs_material_logs','crs_claims','crs_rental_assets','crs_rentals','crs_rental_items']
  loop
    execute format(
      'create policy "crs members" on public.%I for all to authenticated
         using (crs_private.is_member()) with check (crs_private.is_member())', t);
  end loop;
end $$;

-- Profiles: members see the roster; users may only rename themselves.
