-- ---------- LINE notify shared secret ----------
-- The DB sends this in x-notify-secret; the crs-line-notify edge function checks
-- it through crs_notify_secret_ok() (service role only), so the value lives in
-- one place and never needs copying into edge secrets.

select vault.create_secret(encode(extensions.gen_random_bytes(32), 'hex'), 'crs_line_notify_secret');

create function public.crs_notify_secret_ok(p text) returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from vault.decrypted_secrets
    where name = 'crs_line_notify_secret' and decrypted_secret = p
  )
$$;
revoke execute on function public.crs_notify_secret_ok(text) from public, anon, authenticated;
grant execute on function public.crs_notify_secret_ok(text) to service_role;

